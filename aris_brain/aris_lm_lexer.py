    def tokenize(self, text: str) -> List[Token]:
        """分词: 正向最大匹配 + 未登录词处理"""
        tokens = []
        i = 0
        while i < len(text):
            matched = False
            # 尝试最长匹配
            for word in self._sorted_words:
                if text[i:i+len(word)] == word:
                    pos = self._word_dict[word]
                    tokens.append(Token(word, pos, i, i+len(word)))
                    i += len(word)
                    matched = True
                    break
            
            if not matched:
                # 未登录词: 按单字处理
                ch = text[i]
                if ch.strip():
                    pos = 'unk'
                    if '\u4e00' <= ch <= '\u9fff':
                        pos = 'n'  # 未知汉字默认为名词
                    elif ch in '，。！？；：""''「」【】（）、':
                        pos = 'punc'
                    elif ch in '…—～·':
                        pos = 'punc'
                    tokens.append(Token(ch, pos, i, i+1))
                i += 1
        
        return tokens


